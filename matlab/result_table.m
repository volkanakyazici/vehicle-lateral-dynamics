function T = result_table(c,p,x,request,delta)
% Derived quantities use the same signs and SI units as the plant.
a=p.front_distance_m; b=p.rear_distance_m; U=c.U;
af=delta-(x(:,1)+a*x(:,2))/U; ar=-(x(:,1)-b*x(:,2))/U;
Fyf=p.front_axle_stiffness_Nprad*af; Fyr=p.rear_axle_stiffness_Nprad*ar;
ay=(Fyf+Fyr)/p.mass_kg;
T=table(c.t,U*c.t,x(:,4),c.yref,x(:,1),x(:,2),x(:,3),c.slope,c.xref(:,3), ...
    x(:,1)/U,request,delta,af,ar,Fyf,Fyr,ay,x(:,4)-c.yref,x(:,3)-c.slope,c.curvature, ...
    'VariableNames',{'time_s','X_m','Y_m','Y_ref_m','vy_mps','yaw_rate_radps','psi_rad', ...
    'road_heading_rad','body_heading_ref_rad','beta_rad','delta_request_rad','delta_rad', ...
    'alpha_f_rad','alpha_r_rad','Fyf_N','Fyr_N','ay_mps2','ey_m','epsi_road_rad','curvature_1pm'});
end
